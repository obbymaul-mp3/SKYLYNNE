# SKYLYNNE: the tables of the sound (firmware/src/sk_dsp.c, sk_fx.c), at 44.1 kHz:
#   SK_W[note]    the pole angle of a MIDI note in Q29 radians (the resonators)
#   SK_R[i]       the pole radius for a ring-out time constant of 0.03 s * 1.28^i, in Q29; SK_TAU[i]: that, in samples
#   SK_INC[note]  an oscillator's phase step, 2^32 a cycle (the FM voices)
#   SK_PER[note]  samples a period in Q16 (the plucked strings)
#   SK_SIN[1024]  one sine cycle in Q15
#   SK_HANN[256]  a half-sine window in Q15 (the grains)
#   SK_RVG[32]    the reverb's loop gain (Q15) for 32 decay times, for loops of about 2400 samples
#   python3 tools/gen_sky_tables.py > firmware/src/sky_tables.h
import math
FS = 44100.0
out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
       "/* generated by tools/gen_sky_tables.py: do not edit */"]


def emit(decl, vals, per=8):
    out.append(decl + " = {")
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(vals[i:i + per]) + ",")
    out.append("};")


def hz(n):
    return 440.0 * 2 ** ((n - 69) / 12.0)


emit("static const uint32_t SK_W[128]",
     [str(min(int(round(2 * math.pi * hz(n) / FS * 2 ** 29)), 0xFFFFFFFF)) + "u" for n in range(128)])
emit("static const int32_t SK_R[24]",
     [str(int(round(math.exp(-1.0 / (0.03 * 1.28 ** i * FS)) * 2 ** 29))) for i in range(24)], 6)
emit("static const uint32_t SK_TAU[24]", [str(int(round(0.03 * 1.28 ** i * FS))) + "u" for i in range(24)], 6)
emit("static const uint32_t SK_INC[128]", [str(min(int(round(hz(n) / FS * 2 ** 32)), 0xFFFFFFFF)) + "u" for n in range(128)])
emit("static const uint32_t SK_PER[128]", [str(min(int(round(FS / hz(n) * 65536)), 0xFFFFFFFF)) + "u" for n in range(128)])
emit("static const int16_t SK_SIN[1024]", [str(int(round(math.sin(2 * math.pi * i / 1024) * 32767))) for i in range(1024)], 16)
emit("static const int16_t SK_HANN[256]", [str(int(round(math.sin(math.pi * (i + 0.5) / 256) ** 2 * 32767))) for i in range(256)], 16)
rv = []
for i in range(32):
    rt = 0.4 * 1.2 ** i                      # 0.4 s .. ~120 s (the top steps are "forever")
    g = 10 ** (-3 * 2400 / (rt * FS))
    rv.append(str(int(round(min(g, 0.9985) * 32767))))
emit("static const int16_t SK_RVG[32]", rv, 8)
print("\n".join(out))
